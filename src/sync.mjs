import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadConfig } from "./config.mjs";
import { collect, fileLabel } from "./collect.mjs";
import { discover } from "./discover.mjs";
import { resolveSources } from "./sources.mjs";
import { exists, git, parseFrontmatter, toPosix } from "./util.mjs";

export const marker = "Generated by multi-agent-kit";
// Files written by the per-project sync scripts that multi-agent-kit replaces.
const legacyMarkers = ["Generated by workspace/tools/sync-agent-kit.mjs", "Generated by tools/sync-agent-kit.mjs"];
const PLATFORM_ROOTS = { cursor: [".cursor"], claude: [".claude"], codex: [".codex", ".agents"] };
const ALL_ROOTS = [".cursor", ".claude", ".codex", ".agents"];
const MANIFEST = ".agent-kit-manifest.json";
const STATE_DIRECTORY = ".multi-agent-kit";
const PRIVATE_MANIFEST = `${STATE_DIRECTORY}/private-manifest.json`;
const EXCLUDE_START = "# multi-agent-kit:private:start";
const EXCLUDE_END = "# multi-agent-kit:private:end";

const escapeToml = (value) => String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\n", "\\n");

export function generatedMarkdown(label, markdown) {
  const generatedMarker = `<!-- ${marker}. Source: ${label} -->\n`;
  if (!markdown.startsWith("---\n")) return `${generatedMarker}${markdown}`;
  const end = markdown.indexOf("\n---\n", 4);
  if (end === -1) return `${generatedMarker}${markdown}`;
  const frontmatterEnd = end + 5;
  return `${markdown.slice(0, frontmatterEnd)}${generatedMarker}${markdown.slice(frontmatterEnd)}`;
}

export function stripMarker(markdown) {
  return markdown.replace(/<!-- Generated by [^>]*?\. Source: [^>]*? -->\n/, "");
}

function generatedJson(label, value) {
  return `${JSON.stringify({ _agentKit: { generatedBy: marker, source: label }, ...value }, null, 2)}\n`;
}

function skillDocument(name, label, markdown) {
  const { attributes, body } = parseFrontmatter(markdown);
  const description = attributes.description || `Generated from the ${name} command source.`;
  return `---\nname: ${name}\ndescription: ${description}\n---\n\n${generatedMarkdown(label, body)}`;
}

function codexAgent(label, markdown) {
  const { attributes, body } = parseFrontmatter(markdown);
  if (!attributes.name || !attributes.description) {
    throw new Error(`${label} must define name and description in YAML frontmatter`);
  }
  const lines = [
    `# ${marker}. Source: ${label}`,
    `name = "${escapeToml(attributes.name)}"`,
    `description = "${escapeToml(attributes.description)}"`,
  ];
  if (attributes.model && attributes.model !== "inherit") lines.push(`model = "${escapeToml(attributes.model)}"`);
  if (attributes.readonly === "true") lines.push('sandbox_mode = "read-only"');
  // TOML basic strings interpret backslashes, so escape them before the closing-quote guard.
  const instructions = body.replaceAll("\\", "\\\\").replaceAll('"""', '""\\"');
  lines.push(`developer_instructions = """${instructions}"""`);
  return `${lines.join("\n")}\n`;
}

export async function isOwned(filePath) {
  if (!await exists(filePath)) return false;
  const content = await readFile(filePath, "utf8");
  if ([marker, ...legacyMarkers].some((text) => content.includes(text))) return true;
  try {
    const generatedBy = JSON.parse(content)?._agentKit?.generatedBy;
    return [marker, ...legacyMarkers].includes(generatedBy);
  } catch {
    return false;
  }
}

function withManagedWorkflow(current, workflow) {
  const block = `<!-- agent-kit-workflow:start -->\n${workflow.trim()}\n<!-- agent-kit-workflow:end -->`;
  const pattern = /<!-- agent-kit-workflow:start -->[\s\S]*?<!-- agent-kit-workflow:end -->/;
  if (pattern.test(current)) return current.replace(pattern, block);
  return `${current.trimEnd()}\n\n${block}\n`;
}

function renderer(config, defaults) {
  const values = {
    mak: {
      project: config.name,
      local: config.local || "(локальный слой не задан в multi-agent-kit.json)",
      decisions: config.decisions?.directory || "(decisions не заданы в multi-agent-kit.json)",
      scopes: config.decisions?.scopes?.join(", ") || "",
      cli: config.cli,
    },
    vars: { ...defaults, ...config.vars },
  };
  return (text, label) => text.replace(/\{\{\s*(mak|vars)\.([A-Za-z0-9_-]+)\s*\}\}/g, (whole, group, key) => {
    const value = values[group][key];
    if (value === undefined) throw new Error(`${label}: unknown variable ${whole}; define it in multi-agent-kit.json "vars"`);
    return String(value);
  });
}

// Builds the full set of desired outputs without touching the disk.
export async function plan(root, options = {}) {
  const config = await loadConfig(root);
  const sources = await resolveSources(root, config, options);
  const { items, shadows, defaults } = await collect(root, config, sources);
  const render = renderer(config, defaults);
  const targets = new Set(config.targets);
  const outputs = new Map();

  const emit = (relative, content, meta) => {
    if (outputs.has(relative)) throw new Error(`Duplicate output: ${relative}`);
    outputs.set(relative, { content, private: meta.private, source: meta.source ?? null });
  };
  const read = async (item, file) => render(await readFile(file.absolute, "utf8"), fileLabel(item, file));
  const meta = (item, file, reversible = true) => ({
    private: item.origin.private,
    source: reversible ? { absolute: file.absolute, label: fileLabel(item, file), writable: item.origin.writable } : null,
  });
  const byKind = (kind) => [...items.values()].filter((item) => item.kind === kind).sort((a, b) => a.id.localeCompare(b.id));

  for (const item of byKind("skills")) {
    for (const file of item.files) {
      const content = generatedMarkdown(fileLabel(item, file), await read(item, file));
      const relative = `skills/${file.relative}`;
      if (targets.has("cursor")) emit(`.cursor/${relative}`, content, meta(item, file));
      if (targets.has("claude")) emit(`.claude/${relative}`, content, meta(item, file));
      if (targets.has("codex")) emit(`.agents/${relative}`, content, meta(item, file));
    }
  }

  for (const item of byKind("agents")) {
    const [file] = item.files;
    const label = fileLabel(item, file);
    const content = await read(item, file);
    if (file.relative.endsWith(".md")) {
      if (targets.has("cursor")) emit(`.cursor/agents/${item.name}.md`, generatedMarkdown(label, content), meta(item, file));
      if (targets.has("claude")) emit(`.claude/agents/${item.name}.md`, generatedMarkdown(label, content), meta(item, file));
      if (targets.has("codex")) emit(`.codex/agents/${item.name}.toml`, codexAgent(label, content), meta(item, file, false));
    } else {
      // A Cursor always-applied agent is a rule, not a Codex/Claude subagent.
      if (targets.has("cursor")) emit(`.cursor/rules/${item.name}.mdc`, generatedMarkdown(label, content), meta(item, file));
      if (targets.has("claude")) emit(`.claude/rules/${item.name}.md`, generatedMarkdown(label, content), meta(item, file));
    }
  }

  for (const item of byKind("commands")) {
    const [file] = item.files;
    const label = fileLabel(item, file);
    const content = await read(item, file);
    if (targets.has("cursor")) emit(`.cursor/commands/${item.name}.md`, generatedMarkdown(label, content), meta(item, file));
    const skill = skillDocument(item.name, label, content);
    if (targets.has("cursor")) emit(`.cursor/skills/${item.name}/SKILL.md`, skill, meta(item, file, false));
    if (targets.has("claude")) emit(`.claude/skills/${item.name}/SKILL.md`, skill, meta(item, file, false));
    if (targets.has("codex")) emit(`.agents/skills/${item.name}/SKILL.md`, skill, meta(item, file, false));
  }

  for (const kind of ["rules", "context"]) {
    for (const item of byKind(kind)) {
      const [file] = item.files;
      const content = generatedMarkdown(fileLabel(item, file), await read(item, file));
      if (targets.has("cursor")) emit(`.cursor/${kind}/${file.relative}`, content, meta(item, file));
      if (kind === "rules" && targets.has("claude")) emit(`.claude/rules/${file.relative.replace(/\.mdc$/, ".md")}`, content, meta(item, file));
    }
  }

  const workflowItem = items.get("context/agent-kit-workflow");
  if (workflowItem) {
    const [file] = workflowItem.files;
    let workflow = await read(workflowItem, file);
    const decisionsItem = items.get("context/decisions");
    if (config.decisions && decisionsItem) workflow += `\n\n${await read(decisionsItem, decisionsItem.files[0])}`;
    const label = fileLabel(workflowItem, file);
    const frontmatter = "---\ndescription: Управление capabilities через единый agent-kit.\nalwaysApply: true\n---\n";
    const workflowMeta = { private: workflowItem.origin.private };
    if (targets.has("cursor")) emit(".cursor/rules/agent-kit-workflow.mdc", `${frontmatter}${generatedMarkdown(label, workflow)}`, workflowMeta);
    if (targets.has("claude")) emit(".claude/rules/agent-kit-workflow.md", `${frontmatter}${generatedMarkdown(label, workflow)}`, workflowMeta);
    const agentsFile = path.join(root, "AGENTS.md");
    const current = await exists(agentsFile) ? await readFile(agentsFile, "utf8") : `# ${config.name}\n`;
    emit("AGENTS.md", withManagedWorkflow(current, workflow), workflowMeta);
  }

  const mcpItems = byKind("mcp");
  if (mcpItems.length) {
    const mcpServers = {};
    for (const item of mcpItems) {
      Object.assign(mcpServers, JSON.parse(await read(item, item.files[0])).mcpServers || {});
    }
    const label = mcpItems.map((item) => fileLabel(item, item.files[0])).join(", ");
    const mcpMeta = { private: mcpItems.some((item) => item.origin.private) };
    if (targets.has("cursor")) emit(".cursor/mcp.json", generatedJson(label, { mcpServers }), mcpMeta);
    // Claude Code reads project-scoped MCP servers from .mcp.json at the repository root
    // and skips URL servers without an explicit transport type.
    const claudeServers = Object.fromEntries(
      Object.entries(mcpServers).map(([name, server]) => [name, server.url && !server.type ? { type: "http", ...server } : server]),
    );
    if (targets.has("claude")) emit(".mcp.json", generatedJson(label, { mcpServers: claudeServers }), mcpMeta);
    if (targets.has("codex")) {
      const toml = [`# ${marker}. Source: ${label}`];
      for (const [name, server] of Object.entries(mcpServers)) {
        toml.push("", `[mcp_servers."${escapeToml(name)}"]`);
        if (server.url) toml.push(`url = "${escapeToml(server.url)}"`);
        if (server.command) toml.push(`command = "${escapeToml(server.command)}"`);
        if (Array.isArray(server.args)) toml.push(`args = [${server.args.map((argument) => `"${escapeToml(argument)}"`).join(", ")}]`);
        if (server.env && typeof server.env === "object") {
          toml.push("env = { " + Object.entries(server.env).map(([key, value]) => `${key} = "${escapeToml(value)}"`).join(", ") + " }");
        }
      }
      emit(".codex/config.toml", `${toml.join("\n")}\n`, mcpMeta);
    }
  }

  // A project that commits private files treats them like any other generated file.
  if (config.commitPrivate) for (const output of outputs.values()) output.private = false;

  const activeRoots = [...new Set(config.targets.flatMap((target) => PLATFORM_ROOTS[target]))];
  for (const platformRoot of activeRoots) {
    const files = [...outputs].filter(([file, output]) => file.startsWith(`${platformRoot}/`) && !output.private).map(([file]) => file);
    emit(`${platformRoot}/${MANIFEST}`, generatedJson("multi-agent-kit", { files: files.sort() }), { private: false });
  }

  return { config, sources, items, shadows, outputs, activeRoots };
}

function gitContext(root) {
  const top = git(root, ["rev-parse", "--show-toplevel"]);
  if (top.status !== 0) return null;
  const exclude = git(root, ["rev-parse", "--git-path", "info/exclude"]);
  const toplevel = top.stdout.trim();
  return {
    toplevel,
    prefix: toPosix(path.relative(toplevel, root)),
    excludeFile: path.resolve(root, exclude.stdout.trim()),
  };
}

function trackedFiles(root, files) {
  if (!files.length) return [];
  const result = git(root, ["ls-files", "-z", "--", ...files]);
  return result.status === 0 ? result.stdout.split("\0").filter(Boolean) : [];
}

async function readManifest(root, relative) {
  const file = path.join(root, relative);
  if (!await exists(file)) return [];
  try {
    return JSON.parse(await readFile(file, "utf8")).files || [];
  } catch {
    throw new Error(`Cannot read generated manifest: ${relative}`);
  }
}

async function findStale(root, outputs, activeRoots) {
  const stale = [];
  for (const platformRoot of ALL_ROOTS) {
    for (const oldFile of await readManifest(root, `${platformRoot}/${MANIFEST}`)) {
      if (!oldFile.startsWith(`${platformRoot}/`) || oldFile.split("/").includes("..") || path.isAbsolute(oldFile)) {
        throw new Error(`Unsafe manifest path: ${oldFile}`);
      }
      if (!outputs.has(oldFile) && await isOwned(path.join(root, oldFile))) stale.push(oldFile);
    }
    const manifest = `${platformRoot}/${MANIFEST}`;
    if (!activeRoots.includes(platformRoot) && await isOwned(path.join(root, manifest))) stale.push(manifest);
  }
  for (const oldFile of await readManifest(root, PRIVATE_MANIFEST)) {
    if (!ALL_ROOTS.some((platformRoot) => oldFile.startsWith(`${platformRoot}/`)) && ![".mcp.json"].includes(oldFile)) continue;
    if (oldFile.split("/").includes("..")) continue;
    if (!outputs.has(oldFile) && !stale.includes(oldFile) && await isOwned(path.join(root, oldFile))) stale.push(oldFile);
  }
  return stale;
}

async function updateExclude(context, privateFiles) {
  const lines = [`/${STATE_DIRECTORY}/`, ...privateFiles.sort()].map((file) => `/${[context.prefix, file.replace(/^\//, "")].filter(Boolean).join("/")}`);
  const block = `${EXCLUDE_START}\n${lines.join("\n")}\n${EXCLUDE_END}`;
  const current = await exists(context.excludeFile) ? await readFile(context.excludeFile, "utf8") : "";
  const pattern = new RegExp(`${EXCLUDE_START}[\\s\\S]*?${EXCLUDE_END}`);
  const next = pattern.test(current) ? current.replace(pattern, block) : `${current.trimEnd()}${current.trim() ? "\n\n" : ""}${block}\n`;
  if (next !== current) {
    await mkdir(path.dirname(context.excludeFile), { recursive: true });
    await writeFile(context.excludeFile, next, "utf8");
  }
}

// takeOver: hand-made copies that equal their source become generated files (migration from copies).
export async function sync(root, { check = false, update = false, takeOver = false, warn = console.warn } = {}) {
  const result = await plan(root, { update, warn });
  const { config, outputs, activeRoots } = result;

  const changed = [];
  const conflicts = [];
  const takenOver = [];
  for (const [relative, output] of outputs) {
    const destination = path.join(root, relative);
    const actual = await exists(destination) ? await readFile(destination, "utf8") : undefined;
    if (actual !== undefined && actual !== output.content && relative !== "AGENTS.md" && !await isOwned(destination)) {
      if (takeOver && actual === stripMarker(output.content)) takenOver.push(relative);
      else conflicts.push(relative);
    }
    if (actual !== output.content) changed.push(relative);
  }
  if (conflicts.length) {
    const hint = takeOver
      ? "these files differ from their source: keep the project version with \"multi-agent-kit adopt <file>\" or delete the file to take the source version, then sync again"
      : "these files were not generated by multi-agent-kit; run \"multi-agent-kit sync --take-over\" to take over copies that equal their source";
    throw new Error(`Refusing to overwrite ${conflicts.length} unowned files (${hint}):\n  ${conflicts.join("\n  ")}`);
  }
  const stale = await findStale(root, outputs, activeRoots);
  const privateFiles = [...outputs].filter(([, output]) => output.private).map(([file]) => file);
  const context = gitContext(root);
  const trackedPrivate = context && !config.commitPrivate ? trackedFiles(root, privateFiles) : [];
  const discovered = await discover(root, outputs, config.targets);

  if (check) return { ...result, changed, stale, trackedPrivate, takenOver, discovered, written: false };

  for (const relative of stale) await rm(path.join(root, relative));
  for (const relative of changed) {
    const destination = path.join(root, relative);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, outputs.get(relative).content, "utf8");
  }
  const stateDirectory = path.join(root, STATE_DIRECTORY);
  await mkdir(stateDirectory, { recursive: true });
  await writeFile(path.join(stateDirectory, ".gitignore"), "*\n", "utf8");
  await writeFile(path.join(root, PRIVATE_MANIFEST), `${JSON.stringify({ files: privateFiles.sort() }, null, 2)}\n`, "utf8");
  if (context) await updateExclude(context, privateFiles);
  return { ...result, changed, stale, trackedPrivate, takenOver, discovered, written: true };
}
