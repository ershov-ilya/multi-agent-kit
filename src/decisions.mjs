import { readFile, readdir, mkdir, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { loadDecisionsConfig } from "./config.mjs";

const USAGE = "Usage: decisions create RFC|ADR|OPS scope topic [--adr NNNN] | decisions index";

export async function decisions(root, argv) {
  const config = await loadDecisionsConfig(root);
  const directory = path.resolve(root, config.directory);
  if (!directory.startsWith(root + path.sep) || !Array.isArray(config.scopes)) throw Error("Invalid decisions configuration");
  const [command, type, scope, topic, ...options] = argv;
  const pattern = /^(\d{4})-(RFC|ADR|OPS)-([a-z0-9-]+)\.md$/;
  await mkdir(directory, { recursive: true });
  const lock = path.join(directory, ".decisions.lock");
  await mkdir(lock); // Exclusive lock: concurrent allocation fails rather than reusing an ID.
  let created = null;
  try {
    const files = (await readdir(directory)).filter((name) => pattern.test(name)).sort();
    if (command === "create") {
      if (!["RFC", "ADR", "OPS"].includes(type) || !config.scopes.includes(scope) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(topic || "")) {
        throw Error(`${USAGE}\nScopes: ${config.scopes.join(", ")}`);
      }
      let number = Math.max(0, ...files.map((name) => Number(name.slice(0, 4)))) + 1;
      let related = "";
      if (options.length) {
        if (type !== "OPS" || options.length !== 2 || options[0] !== "--adr" || !/^\d{4}$/.test(options[1])) throw Error("Only OPS accepts --adr NNNN");
        related = `${options[1]}-ADR-${scope}-${topic}.md`;
        if (!files.includes(related)) throw Error("Matching ADR not found");
        number = Number(options[1]);
      }
      if (number > 9999) throw Error("Decision number range exhausted");
      const name = `${String(number).padStart(4, "0")}-${type}-${scope}-${topic}.md`;
      const metadata = type === "ADR" ? "status: accepted\nimplementation: pending\nsupersedes: []" : type === "RFC" ? "status: draft" : `related_adr: ${related || "TODO"}`;
      await writeFile(path.join(directory, name), `---\ntitle: ${topic}\n${metadata}\n---\n\n# ${type}: ${topic}\n\n## Контекст\n\nTODO\n\n## ${type === "OPS" ? "Опыт и проверки" : "Решение"}\n\nTODO\n`, { flag: "wx" });
      files.push(name);
      files.sort();
      created = path.relative(root, path.join(directory, name));
    } else if (command !== "index" || type) throw Error(USAGE);
    const rows = [];
    for (const name of files) {
      const content = await readFile(path.join(directory, name), "utf8");
      const status = content.match(/^status:\s*(.+)$/m)?.[1] || "—";
      const implementation = content.match(/^implementation:\s*(.+)$/m)?.[1] || (status === "done" ? "done" : "—");
      rows.push(`| ${name.slice(0, 4)} | [${name}](${name}) | ${status === "done" ? "accepted" : status} | ${implementation} |`);
    }
    await writeFile(path.join(directory, "ACTIVE.md"), `# Индекс решений\n\n<!-- Generated by multi-agent-kit decisions -->\n\n| ID | Документ | Статус | Внедрение |\n|----|----------|--------|-----------|\n${rows.join("\n")}\n`);
  } finally {
    await rm(lock, { recursive: true });
  }
  return created;
}
