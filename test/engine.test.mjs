test("stale files, conflicts and adopt", async () => {
  const { base, project, publicKit } = await fixture();
  const run = runner(project);
  try {
    run(["sync"]);
    await write(publicKit, "packs/product/skills/extra/SKILL.md", "---\nname: extra\ndescription: Extra\n---\n\nExtra.\n");
    run(["check"], false);
    run(["sync"]);
    await rm(path.join(publicKit, "packs/product/skills/extra"), { recursive: true });
    run(["sync"]);
    await assert.rejects(access(path.join(project, ".claude/skills/extra/SKILL.md")));

    const generated = path.join(project, ".claude/skills/nudge/SKILL.md");
    await writeFile(generated, (await readFile(generated, "utf8")).replace("Local nudge.", "Local nudge, improved."));
    assert.match(run(["check"], false), /adopt/);
    assert.match(run(["adopt", ".claude/skills/nudge/SKILL.md"]), /adopted/);
    const source = await readFile(path.join(project, "agent-kit/skills/nudge/SKILL.md"), "utf8");
    assert.match(source, /improved/);
    assert.doesNotMatch(source, /Generated by/);
    run(["sync"]);
    run(["check"]);
    assert.match(run(["adopt", ".claude/rules/deploy.md"]), /unchanged/);

    await writeFile(path.join(project, ".cursor/commands/adr.md"), "User-owned content");
    assert.match(run(["sync"], false), /--take-over/);
    assert.equal(await readFile(path.join(project, ".cursor/commands/adr.md"), "utf8"), "User-owned content");
    assert.match(run(["sync", "--take-over"], false), /differ from their source[\s\S]*\.cursor\/commands\/adr\.md/);
    await writeFile(path.join(project, ".cursor/commands/adr.md"), "---\ndescription: Record a decision\n---\n\nUse docs/decisions.\n");
    assert.match(run(["sync", "--take-over"]), /took over 1/);
    assert.match(await readFile(path.join(project, ".cursor/commands/adr.md"), "utf8"), /Generated by multi-agent-kit/);
  } finally {
    await rm(base, { recursive: true });
  }
});

