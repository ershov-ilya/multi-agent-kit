test("git sources are cloned into the cache and refreshed with --update", async () => {
  const { base, project, privateKit, config } = await fixture();
  const run = runner(project);
  const gitIn = (args) => spawnSync("git", args, { cwd: privateKit, encoding: "utf8" });
  try {
    gitIn(["init", "-q", "-b", "main"]);
    gitIn(["add", "."]);
    gitIn(["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "init"]);
    const sources = [config.sources[0], { git: privateKit, ref: "main", private: true }];
    await writeFile(path.join(project, "multi-agent-kit.json"), JSON.stringify({ ...config, sources }));
    run(["sync"]);
    assert.match(await readFile(path.join(project, ".claude/skills/founder/SKILL.md"), "utf8"), /Secret plans/);
    await write(privateKit, "packs/personal/skills/founder/SKILL.md", "---\nname: founder\ndescription: Founder context\n---\n\nNew plans.\n");
    gitIn(["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qam", "update"]);
    run(["sync"]);
    assert.match(await readFile(path.join(project, ".claude/skills/founder/SKILL.md"), "utf8"), /Secret plans/);
    run(["sync", "--update"]);
    assert.match(await readFile(path.join(project, ".claude/skills/founder/SKILL.md"), "utf8"), /New plans/);
    assert.match(run(["adopt", ".claude/skills/founder/SKILL.md"]), /unchanged/);
  } finally {
    await rm(base, { recursive: true });
  }
});

