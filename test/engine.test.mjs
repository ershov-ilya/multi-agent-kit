import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile, rm, access } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const cli = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../bin/multi-agent-kit.mjs");

async function write(root, relative, content) {
  await mkdir(path.dirname(path.join(root, relative)), { recursive: true });
  await writeFile(path.join(root, relative), content);
}

function runner(root) {
  return (args, success = true) => {
    const result = spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: "utf8", env: { ...process.env, MULTI_AGENT_KIT_CACHE: path.join(root, ".cache") } });
    assert.equal(result.status === 0, success, `${args.join(" ")}\n${result.stderr}${result.stdout}`);
    return result.stdout + result.stderr;
  };
}

