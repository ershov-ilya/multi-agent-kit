test("layers, overrides, variables and platform outputs", async () => {
  const { base, project } = await fixture();
  const run = runner(project);
  try {
    const output = run(["sync"]);
    assert.match(output, /overrides skills\/nudge: local:agent-kit replaces pub:product/);
    assert.match(output, /skipped optional source/);
    const read = (relative) => readFile(path.join(project, relative), "utf8");
    assert.match(await read(".claude/skills/nudge/SKILL.md"), /Local nudge/);
    await access(path.join(project, ".agents/skills/seogeo/SKILL.md"));
    await assert.rejects(access(path.join(project, ".claude/skills/octalysis/SKILL.md")));
    assert.match(await read(".claude/rules/deploy.md"), /Host prod\.example/);
    assert.match(await read(".cursor/rules/deploy.mdc"), /Generated by multi-agent-kit\. Source: local:agent-kit\/rules\/deploy\.mdc/);
    const agents = await read("AGENTS.md");
    assert.match(agents, /Own text\./);
    assert.match(agents, /Workflow for demo[\s\S]*Decisions in docs\/decisions/);
    const toml = await read(".codex/agents/reviewer.toml");
    assert.match(toml, /description = "Reviews documents carefully\."/);
    assert.match(toml, /sandbox_mode = "read-only"/);
    assert.match(toml, /""\\"quoted/);
    assert.equal(JSON.parse(await read(".mcp.json")).mcpServers.memory.type, "http");
    assert.match(await read(".claude/skills/adr/SKILL.md"), /Use docs\/decisions\./);
    run(["check"]);
  } finally {
    await rm(base, { recursive: true });
  }
});

test("private outputs stay out of git and out of public manifests", async () => {
  const { base, project } = await fixture();
  const run = runner(project);
  try {
    run(["sync"]);
    const manifest = await readFile(path.join(project, ".claude/.agent-kit-manifest.json"), "utf8");
    assert.doesNotMatch(manifest, /founder/);
    const exclude = await readFile(path.join(project, ".git/info/exclude"), "utf8");
    assert.match(exclude, /\/\.claude\/skills\/founder\/SKILL\.md/);
    assert.match(exclude, /\/\.multi-agent-kit\//);
    const status = spawnSync("git", ["status", "--porcelain", "--untracked-files=all"], { cwd: project, encoding: "utf8" }).stdout;
    assert.doesNotMatch(status, /founder/);
    spawnSync("git", ["add", "-f", ".claude/skills/founder/SKILL.md"], { cwd: project });
    assert.match(run(["check"], false), /private files are tracked/);
  } finally {
    await rm(base, { recursive: true });
  }
});

